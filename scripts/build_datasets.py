def is_genai(ds):
    return bool(ds.get('genai'))


def dataset_cards(data, datasets):
    cards = []
    for ds in datasets:
        facts = ''.join(f'<li><span>{esc(k)}</span> {esc(v)}</li>' for k, v in ds.get('facts', []))
        new = '<span class="tag tag-accent">New</span>' if ds.get('new') else ''
        cards.append(f'''          <article class="dataset-card">
            <a class="dataset-card-media" href="{esc(ds['slug'])}.html" tabindex="-1" aria-hidden="true"><img src="{esc(local(ds['image']))}" alt="" loading="lazy"></a>
            <div class="dataset-card-body">
              <div class="card-tags">{new}<span class="tag">{esc(data['license']['short'])}</span></div>
              <h3 class="dataset-card-title"><a href="{esc(ds['slug'])}.html">{esc(ds['name'])}</a></h3>
              <p>{esc(ds['summary'])}</p>
              <ul class="dataset-facts">{facts}</ul>
              <div class="dataset-actions">
                {download_button(ds)}
                <a href="{esc(ds['slug'])}.html" class="btn btn-ghost">Details</a>
              </div>
            </div>
          </article>''')
    return '\n'.join(cards)


def collection_card(kicker, title, href, summary, image, datasets):
    names = ''.join(f'<li><a href="{esc(ds["slug"])}.html">{esc(ds["name"])}</a></li>' for ds in datasets)
    count = f'{len(datasets)} dataset' + ('s' if len(datasets) != 1 else '')
    return f'''          <article class="dataset-card">
            <a class="dataset-card-media" href="{esc(href)}" tabindex="-1" aria-hidden="true"><img src="{esc(local(image))}" alt="" loading="lazy"></a>
            <div class="dataset-card-body">
              <p class="card-kicker">{esc(kicker)} · {count}</p>
              <h2 class="dataset-card-title"><a href="{esc(href)}">{esc(title)}</a></h2>
              <p>{esc(summary)}</p>
              <ul class="dataset-facts">{names}</ul>
              <div class="dataset-actions">
                <a href="{esc(href)}" class="btn btn-primary">Explore {esc(title)}</a>
              </div>
            </div>
          </article>'''


def index_page(data):
    """Landing page of the section: one card per collection (the same two pages as the menu)."""
    mirage, genai = data['datasets'], [ds for ds in data['datasets'] if is_genai(ds)]
    image = lambda items: items[0]['image'] if items else ''
    cards = '\n'.join([
        collection_card('Project', 'MIRAGE project', 'mirage.html', data['intro'], image(mirage[::-1]), mirage),
        collection_card('Projects', 'GenAI Traffic Projects', 'genai.html', data.get('genai_intro') or GENAI_INTRO, image(genai), genai),
    ])
    main = f'''{hero([('Home', '../index.html'), ('Datasets', '')], 'Datasets',
                'Network traffic datasets with ground truth, released openly to the research community by the Traffic research group.')}

    <section class="section page-body">
      <div class="container">
        <div class="dataset-grid">
{cards}
        </div>
      </div>
    </section>'''
    return frame('Datasets | Traffic', 'Network traffic datasets released by the Traffic research group: the MIRAGE project and the GenAI traffic projects.', main)


