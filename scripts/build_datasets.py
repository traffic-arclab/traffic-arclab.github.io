def esc(text):
    return html.escape(str(text or ''), quote=True)


def local(url):
    """Links in the data are relative to the site root; pages live one folder down."""
    if not url or re.match(r'(https?:|mailto:|#|/)', url):
        return url
    return PREFIX + url


def ext(url):
    return ' target="_blank" rel="noopener"' if re.match(r'https?://', url or '') else ''


def page(data, key):
    """A text of the pages from data["pages"], or its default when it is missing or empty."""
    value = (data.get('pages') or {}).get(key)
    return value if value else PAGE_DEFAULTS[key]


def paras(items, indent=10):
    """Paragraphs (a list, or one string) as <p>, with **bold**."""
    items = [items] if isinstance(items, str) else items
    bold = lambda t: re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', esc(t))
    return '\n'.join(f'{" " * indent}<p>{bold(t)}</p>' for t in items if str(t).strip())


