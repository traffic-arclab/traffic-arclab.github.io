#!/usr/bin/env python3
"""Build the Datasets section of the Traffic site from data/datasets.json.

Generates the Datasets section with the site layout (header, menu and footer
are taken from collaborations.html):

  datasets/index.html   landing page that leads to the two collections below
  datasets/mirage.html  "MIRAGE project": every MIRAGE dataset
  datasets/genai.html   "GenAI Traffic Projects": the datasets marked "genai"
  datasets/<slug>.html  one page per dataset

It also writes the "Datasets" menu of the header (between the DATASETS-MENU
markers) in every page of the site. Every download button opens a short
form (js/datasets.js); the answers are sent to the Google Apps Script web app
set in "form_endpoint" and then the download starts. The files are served by
Zenodo once a dataset has a "zenodo" entry (see scripts/zenodo_upload.py),
otherwise by the address in "file".

The original MIRAGE website in mirage/ is not touched.

Standard library only.
"""
import html
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = {'.git', '.github', 'admin', 'data', 'scripts', 'node_modules'}
MENU_START, MENU_END = '<!-- DATASETS-MENU:START -->', '<!-- DATASETS-MENU:END -->'
# The plain "Datasets" link the header had before the menu (replaced once by the menu).
OLD_LINK = re.compile(r'<li><a href="((?:\.\./)*)datasets/" class="nav-link"(?: aria-current="page")?>Datasets</a></li>')
COLLECTIONS = [
    ('mirage', 'MIRAGE project', 'mirage.html', 'All the MIRAGE mobile-app traffic datasets'),
    ('genai', 'GenAI Traffic Projects', 'genai.html', 'Traffic of Generative AI apps'),
]
GENAI_INTRO = ('Datasets and resources on the network traffic generated by Generative AI apps such as '
               'ChatGPT, Copilot and Gemini, captured with human experimenters and labeled with the generative activity performed.')
DATA = os.path.join(ROOT, 'data', 'datasets.json')
TEMPLATE = os.path.join(ROOT, 'collaborations.html')
OUT = os.path.join(ROOT, 'datasets')
PREFIX = '../'


def esc(text):
    return html.escape(str(text or ''), quote=True)


def local(url):
    """Links in the data are relative to the site root; pages live one folder down."""
    if not url or re.match(r'(https?:|mailto:|#|/)', url):
        return url
    return PREFIX + url


def ext(url):
    return ' target="_blank" rel="noopener"' if re.match(r'https?://', url or '') else ''


# --------------------------------------------------------------------------
# Header menu
# --------------------------------------------------------------------------

MENU_INDENT = ' ' * 10


def render_menu(prefix, current=''):
    mark = lambda key: ' aria-current="page"' if key == current else ''
    links = '\n'.join(
        f'{MENU_INDENT}    <a href="{prefix}datasets/{page}"{mark(key)}>{esc(label)} <small>{esc(note)}</small></a>'
        for key, label, page, note in COLLECTIONS)
    return f'''{MENU_INDENT}<li class="has-dropdown">
{MENU_INDENT}  <button class="nav-link dropdown-toggle" aria-expanded="false">Datasets</button>
{MENU_INDENT}  <div class="dropdown">
{links}
{MENU_INDENT}  </div>
{MENU_INDENT}</li>'''


def replace_block(text, start, end, block, indent):
    return re.sub(re.escape(start) + r'.*?' + re.escape(end),
                  lambda _: f'{start}\n{block}\n{indent}{end}', text, flags=re.S)


def html_pages():
    for folder, dirs, files in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for name in files:
            if name.endswith('.html'):
                yield os.path.join(folder, name)


def update_menus():
    """Writes the Datasets menu in every page with the site header (the pages of datasets/ get it from frame())."""
    count = 0
    for path in html_pages():
        if os.path.dirname(os.path.abspath(path)) == OUT:
            continue
        with open(path, 'rb') as f:
            raw = f.read()
        # Only pages with the site header are touched (some legacy pages are not UTF-8).
        if MENU_START.encode() not in raw and b'class="nav-link">Datasets</a>' not in raw \
                and b'aria-current="page">Datasets</a>' not in raw:
            continue
        page = raw.decode('utf-8')
        prefix = '../' * os.path.relpath(path, ROOT).count(os.sep)
        updated = OLD_LINK.sub(lambda m: f'{MENU_START}\n{MENU_INDENT}{MENU_END}', page)
        if MENU_START not in updated:
            continue
        updated = replace_block(updated, MENU_START, MENU_END, render_menu(prefix), MENU_INDENT)
        count += 1
        if updated != page:
            with open(path, 'w', encoding='utf-8') as f:
                f.write(updated)
    return count


# --------------------------------------------------------------------------
# Page frame from an existing page of the site
# --------------------------------------------------------------------------

def frame(title, description, main, current=''):
    with open(TEMPLATE, encoding='utf-8') as f:
        page = f.read()
    head, rest = page.split('<main id="main">', 1)
    _, tail = rest.split('</main>', 1)
    # The template is a root page: point its relative links one folder up (the content is already right).
    up = lambda part: re.sub(r'(\s(?:href|src))="(?!https?:|//|/|#|mailto:|data:|\.\./)([^"]*)"',
                             lambda m: f'{m.group(1)}="{PREFIX}{m.group(2)}"', part)
    page = up(head) + '<main id="main">\n' + main + '\n  </main>' + up(tail)

    page = re.sub(r'<title>.*?</title>', f'<title>{esc(title)}</title>', page, count=1, flags=re.S)
    page = re.sub(r'<meta name="description" content="[^"]*">',
                  f'<meta name="description" content="{esc(description)}">', page, count=1)
    page = page.replace(' aria-current="page"', '')
    page = replace_block(page, MENU_START, MENU_END, render_menu(PREFIX, current), MENU_INDENT)
    page = page.replace('class="nav-link dropdown-toggle" aria-expanded="false">Datasets</button>',
                        'class="nav-link dropdown-toggle is-current" aria-expanded="false">Datasets</button>')
    page = re.sub(r'(<script src="\.\./js/site\.js(?:\?v=[0-9a-f]*)?" defer></script>)',
                  lambda m: m.group(1) + f'\n  <script src="{PREFIX}js/datasets.js" defer></script>', page, count=1)
    return page


def hero(crumbs, title, lead=''):
    trail = ' <span class="crumb-sep" aria-hidden="true">/</span> '.join(
        f'<a href="{esc(href)}">{esc(label)}</a>' if href else f'<span>{esc(label)}</span>' for label, href in crumbs)
    lead_html = f'\n        <p class="page-lead">{esc(lead)}</p>' if lead else ''
    return f'''    <section class="page-hero">
      <div class="container">
        <nav class="breadcrumb" aria-label="Breadcrumb">{trail}</nav>
        <h1 class="page-title">{esc(title)}</h1>{lead_html}
      </div>
    </section>'''


def download_button(ds, label='Download'):
    return (f'<button type="button" class="btn btn-primary" data-download="{esc(ds["file"])}" '
            f'data-dataset="{esc(ds["name"])}">{esc(label)}'
            + (f' <span class="btn-note">{esc(ds["size"])}</span>' if ds.get('size') else '') + '</button>')


def zenodo_note(ds):
    z = ds.get('zenodo')
    if not z:
        return ''
    return (f'\n            <p class="dataset-host">Hosted on <a href="{esc(z["record"])}" target="_blank" rel="noopener">Zenodo ↗</a>'
            f' · DOI <a href="https://doi.org/{esc(z["doi"])}" target="_blank" rel="noopener">{esc(z["doi"])}</a></p>')


def dataset_doi(ds):
    z = ds.get('zenodo')
    if not z:
        return ''
    return (f'\n          <p>To cite the dataset itself: {esc(ds["name"])}, Zenodo, '
            f'<a href="https://doi.org/{esc(z["doi"])}" target="_blank" rel="noopener">doi:{esc(z["doi"])}</a>.</p>')


