def build():
    with open(DATA, encoding='utf-8') as f:
        data = json.load(f)
    os.makedirs(OUT, exist_ok=True)
    pages = {'index.html': index_page(data), 'mirage.html': mirage_page(data), 'genai.html': genai_page(data)}
    for ds in data['datasets']:
        pages[f'{ds["slug"]}.html'] = dataset_page(data, ds)
    for name, page in pages.items():
        with open(os.path.join(OUT, name), 'w', encoding='utf-8') as f:
            f.write(page)
    return len(pages), update_menus()


if __name__ == '__main__':
    pages, menus = build()
    print(f'Datasets section rebuilt: {pages} pages in datasets/ and the menu of {menus} pages')
