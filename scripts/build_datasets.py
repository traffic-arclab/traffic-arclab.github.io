    c = ds['citation']
    links = ' '.join(f'<a href="{esc(local(link["url"]))}"{ext(link["url"])}>{esc(link["label"])}{" ↗" if ext(link["url"]) else ""}</a>'
                     for link in c.get('links', []))
    new = '<span class="tag tag-accent">New</span>' if ds.get('new') else ''
