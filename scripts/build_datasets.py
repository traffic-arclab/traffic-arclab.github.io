PROMPTS_DIR = os.path.join(ROOT, 'data', 'prompts')


def prompts_of(ds):
    """The prompt set of a dataset, from data/prompts/<slug>.json (None if it has none)."""
    path = os.path.join(PROMPTS_DIR, f'{ds["slug"]}.json')
    if not os.path.exists(path):
        return None
    with open(path, encoding='utf-8') as f:
        return json.load(f)


def short(text, size=90):
    text = re.sub(r'\s*Give me the response as plain text.*$', '', text).strip()
    return text if len(text) <= size else text[:size].rsplit(' ', 1)[0] + '…'


APP_LOGOS = os.path.join(ROOT, 'images', 'apps')
SAME_LOGO = {'zoomcloudmeetings': 'zoom'}   # apps listed under two names


def app_key(name):
    return re.sub(r'[^a-z0-9]', '', name.lower())


def app_logo(name):
    """images/apps/<key>.svg (see scripts/fetch_app_logos.py), or '' when the app has no logo."""
    logo = f'{SAME_LOGO.get(app_key(name), app_key(name))}.svg'
    return f'images/apps/{logo}' if os.path.exists(os.path.join(APP_LOGOS, logo)) else ''


def logo_mark(name, extra=''):
    """The app icon: its logo, or its initial on a colour picked from the name."""
    logo = app_logo(name)
    if logo:
        return f'<span class="app-logo{extra}"><img src="{esc(local(logo))}" alt="" loading="lazy"></span>'
    hue = sum(map(ord, app_key(name))) * 47 % 360
    return f'<span class="app-logo is-initial{extra}" style="--hue: {hue}" aria-hidden="true">{esc(name[:1].upper())}</span>'


def app_entries(apps):
    """The rows of an apps table as dicts: name, package, tags (the other text columns) and store link."""
    cols = [c.lower() for c in apps.get('columns', [])]
    name_col = next((i for i, c in enumerate(cols) if 'app name' in c or c == 'app'), 1)
    entries = []
    for row in apps.get('rows', []):
        tags, link = [], ''
        for i, cell in enumerate(row):
            if isinstance(cell, dict):
                link = cell.get('link', '')
            elif i not in (0, name_col) and str(cell).strip():
                tags += [re.sub(r'\s*\(.*?\)', '', t).strip() for t in str(cell).split(',') if t.strip()]
        entries.append({'name': row[name_col], 'package': row[0] if name_col else '', 'tags': tags, 'link': link})
    return entries


def app_row(app, indent=12):
    pad = ' ' * indent
    tags = ''.join(f'<span class="tag">{esc(t)}</span>' for t in app['tags'])
    store = (f'<a class="app-store" href="{esc(app["link"])}" target="_blank" rel="noopener">Google Play ↗</a>'
             if app['link'] else '')
    return f'''{pad}<li class="app-row">
{pad}  {logo_mark(app['name'])}
{pad}  <span class="app-name"><strong>{esc(app['name'])}</strong><code>{esc(app['package'])}</code>{store}</span>
{pad}  <span class="app-tags">{tags}</span>
{pad}</li>'''


def apps_preview(data, genai):
    """The "Apps and activities" card of the GenAI page: the "genai_apps" list of data/datasets.json
    (edited in the admin page), or else the apps of the GenAI datasets."""
    apps = [{'name': a['name'], 'package': a.get('package', ''), 'tags': a.get('activities', []), 'link': ''}
            for a in data.get('genai_apps') or [] if a.get('name')]
    if not apps:
        apps = [{**app, 'link': ''} for ds in genai for app in app_entries(ds.get('apps') or {})]
    if not apps:
        return ''
    rows = '\n'.join(app_row(app) for app in apps)
    return f"""<aside class="genai-apps">
          <p class="card-kicker">Apps and activities</p>
          <ul class="app-list">
{rows}
          </ul>
        </aside>"""


def apps_wall(datasets, license_short):
    """Every app of the datasets as an icon, plus the activities they were used for."""
    apps, activities = {}, []
    for ds in datasets:
        apps_def = ds.get('apps') or {}
        cols = [c.lower() for c in apps_def.get('columns', [])]
        act_col = next((i for i, c in enumerate(cols) if 'activit' in c), None)
        for app, row in zip(app_entries(apps_def), apps_def.get('rows', [])):
            apps.setdefault(app_logo(app['name']) or app['name'].lower(), (app['name'], ds))   # Zoom = ZOOM Cloud Meetings
            if act_col is not None and act_col < len(row):
                activities += [t.strip() for t in str(row[act_col]).split(',') if t.strip() and t.strip() not in activities]
    ordered = sorted(apps.values(), key=lambda x: (not app_logo(x[0]), x[0].lower()))
    icons = '\n'.join(f'            <li><a href="{esc(ds["slug"])}.html#apps-title" title="{esc(name)} · {esc(ds["name"])}">'
                      f'{logo_mark(name)}<span class="sr-only">{esc(name)}</span></a></li>' for name, ds in ordered)
    chips = ''.join(f'<span class="tag">{esc(a)}</span>' for a in activities)
    chips_html = f'<div class="app-activities"><span class="app-activities-label">Activities</span>{chips}</div>' if chips else ''
    return f"""<aside class="genai-apps">
          <p class="card-kicker">Apps and activities · {len(apps)} apps</p>
          <ul class="app-wall">
{icons}
          </ul>
          {chips_html}
          <p class="genai-apps-source">From {len(datasets)} datasets · all released under {esc(license_short)}</p>
        </aside>"""


def apps_grid(apps):
    rows = '\n'.join(app_row(app, 10) for app in app_entries(apps))
    return f"""        <ul class="app-grid">
{rows}
        </ul>"""


def prompts_preview(genai):
    """One card per GenAI dataset with a prompt set: the prompts at a glance, a link to the answers."""
    cards = []
    for ds in genai:
        p = prompts_of(ds)
        if not p:
            continue
        items = []
        for i, q in enumerate(p['prompts'], 1):
            multimodal = ' is-multimodal' if q.get('activity', '').lower() == 'multimodal' else ''
            items.append(f'<li class="prompt-tile{multimodal}" title="{esc(q["text"])}"><span class="prompt-tile-num">{i:02d}</span>'
                         f'<span class="prompt-tile-label">{esc(q["label"])}</span>'
                         f'<span class="prompt-tile-text">{esc(short(q["text"], 70))}</span></li>')
        logos = ''.join(logo_mark(a['name'], ' app-logo-sm') for a in p['apps'])
        cards.append(f'''          <article class="prompt-set genai-apps">
            <div class="prompt-set-head">
              <p class="card-kicker">Prompt set · {len(p['prompts'])} prompts</p>
              <div class="app-stack" aria-label="Same prompts for {esc(', '.join(a['name'] for a in p['apps']))}">{logos}</div>
            </div>
            <ol class="prompt-tiles">{''.join(items)}</ol>
            <div class="prompt-set-foot">
              <p class="genai-apps-source">From <a href="{esc(ds['slug'])}.html">{esc(ds['name'])}</a> · the same prompts for every app</p>
              <a href="{esc(ds['slug'])}.html#prompts" class="btn btn-primary">Explore prompts and answers →</a>
            </div>
          </article>''')
    return '\n'.join(cards)


def prompt_explorer(ds, p):
    """Every prompt of the set with the answer of each app (the app is chosen with the tabs, see js/datasets.js)."""
    tabs = ''.join(f'<button type="button" role="tab" data-prompt-app="{esc(a["key"])}" aria-selected="false">{esc(a["name"])}</button>'
                   for a in p['apps'])
    names = {a['key']: a['name'] for a in p['apps']}
    items = []
    for i, q in enumerate(p['prompts'], 1):
        # Answers come from the group's own pages (genai_prompts/), so their markup is kept; images get the right path.
        answers = ''.join(
            f'<div class="prompt-answer" data-app="{esc(key)}"><p class="prompt-answer-app">{esc(names.get(key, key))}</p>'
            + re.sub(r'(\ssrc)="(?!https?:|/|\.\./)([^"]*)"', lambda m: f'{m.group(1)}="{PREFIX}{m.group(2)}"', answer)
            + '</div>'
            for key, answer in q['answers'].items())
        items.append(f'''          <details class="prompt-item">
            <summary><span class="prompt-num">{i:02d}</span><span class="prompt-head"><span class="prompt-label">{esc(q['label'])} · {esc(q['activity'])}</span>
            <span class="prompt-text">{esc(short(q['text'], 160))}</span></span></summary>
            <div class="prompt-answers"><p class="prompt-full"><span class="prompt-answer-app">Prompt</span> {esc(q['text'])}</p>{answers}</div>
          </details>''')
    return f'''
    <section class="section page-body" id="prompts" aria-labelledby="prompts-title">
      <div class="container">
        <div class="section-head">
          <h2 id="prompts-title" class="section-title">{esc(p.get('title') or 'Prompts and answers')}</h2>
          <p class="section-intro">{esc(p.get('intro', ''))}</p>
        </div>
        <div class="prompt-explorer" data-prompt-explorer>
          <div class="prompt-tabs" role="tablist" aria-label="App" hidden>{tabs}</div>
{chr(10).join(items)}
        </div>
      </div>
    </section>
'''


