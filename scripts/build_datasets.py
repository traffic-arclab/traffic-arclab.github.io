MENU_NOTES = {}   # notes under the menu entries, set by build() from data["pages"]


def render_menu(prefix, current=''):
    mark = lambda key: ' aria-current="page"' if key == current else ''
    links = '\n'.join(
        f'{MENU_INDENT}    <a href="{prefix}datasets/{href}"{mark(key)}>{esc(label)} <small>{esc(MENU_NOTES.get(key) or note)}</small></a>'
        for key, label, href, note in COLLECTIONS)
